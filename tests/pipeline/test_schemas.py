"""Pydantic contract tests (T02 acceptance: the same fixture passes Pydantic validation + hard constraints).

Covers:
- All core dataset documents (factory-generated since #73) pass the corresponding envelope /
  self-describing model validation
- The three hand-written golden documents (tests/fixtures/{risk,analysis.zh-CN,facts}.json) pass
  their models — they are the cross-language hinge tests/frontend/schemas.test.ts reads
- No implicit fields (extra="forbid")
- Rejects NaN/Infinity
- Strict enum/time validation, numeric range validation
- The factory's output is at least as representative as each golden (structure conformance)
- schema_version support and backward-compatibility check
"""

